#[test]
fn gcm_rejects_length_nonce_ciphertext_and_tag_changes() -> Result<(), PacketProtectionError> {
    let suite = PacketSuite::new(AES128_GCM_OPENSSH, None)?;
    let iv = hex("aabbccddeeff001122334455");
    let key = hex("000102030405060708090a0b0c0d0e0f");
    let mut sender = PacketProtector::new(suite, PacketKeyMaterial::gcm(&iv, &key))?;
    let mut receiver = PacketProtector::new(suite, PacketKeyMaterial::gcm(&iv, &key))?;
    let packet = sender.seal(100, PAYLOAD, BODY_PADDING)?;

    let mut length_change = packet.clone();
    length_change[3] ^= 1;
    assert!(receiver.open(100, &length_change).is_err());
    // RFC 5647's GCM tag binds the clear packet length, not the SSH sequence
    // number. Supplying a different sequence number must not change its nonce.
    assert_eq!(receiver.open(101, &packet)?, PAYLOAD);
    let mut receiver = PacketProtector::new(suite, PacketKeyMaterial::gcm(&iv, &key))?;
    let mut ciphertext_change = packet.clone();
    ciphertext_change[8] ^= 1;
    assert_eq!(
        receiver.open(100, &ciphertext_change),
        Err(PacketProtectionError::AuthenticationFailed)
    );
    let mut tag_change = packet.clone();
    let last = tag_change
        .len()
        .checked_sub(1)
        .ok_or(PacketProtectionError::InvalidPacket)?;
    tag_change[last] ^= 1;
    assert_eq!(
        receiver.open(100, &tag_change),
        Err(PacketProtectionError::AuthenticationFailed)
    );
    assert_eq!(receiver.open(100, &packet)?, PAYLOAD);
    Ok(())
}

