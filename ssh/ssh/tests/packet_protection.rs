#[test]
fn gcm_vectors_match_openssh_across_carries() -> Result<(), PacketProtectionError> {
    // Provenance, stated because getting this wrong is how the two previous
    // versions of this test came to assert constructions neither could refute.
    //
    // The bytes come from OpenSSL, driven through the exact call sequence in
    // OpenSSH's `cipher.c` for `aes128-gcm@openssh.com` and
    // `aes256-gcm@openssh.com`: `cipher_init` hands the derived IV to OpenSSL,
    // `cipher_crypt` advances the counter once per packet, and the four-octet
    // packet length goes in as AAD. Every vector was cross-checked against a
    // from-scratch AES-GCM, itself checked against the NIST GCM test vectors, so
    // the bytes are OpenSSL's and not this crate agreeing with itself.
    //
    // Which invocation counts, and why, is on `GCM_OPENSSH_VECTORS`. The short
    // version: vectors cross the carries where narrower counters would reuse or
    // miscompute a nonce. The SSH sequence numbers used below intentionally do
    // not identify the invocation count.
    //
    // A vector derived from a specification rather than from the peer is only as
    // good as the reading behind it: the two earlier versions of this test were
    // each computed from a different misreading of RFC 5647, and each passed.
    for (iv, cipher, key, cases) in GCM_OPENSSH_VECTORS {
        let iv = hex(iv);
        let key = hex(key);
        let suite = PacketSuite::new(cipher, None)?;
        let mut sender = PacketProtector::new(suite, PacketKeyMaterial::gcm(&iv, &key))?;
        let mut receiver = PacketProtector::new(suite, PacketKeyMaterial::gcm(&iv, &key))?;
        let mut packets_processed = 0_u64;
        for &(invocation, expected) in cases {
            while packets_processed < invocation {
                // The SSH sequence number deliberately does not track the GCM
                // invocation counter: KEX traffic can make them differ.
                let invocation =
                    u32::try_from(packets_processed).expect("test invocation fits in SSH sequence");
                let ssh_sequence = 0xa500_0000_u32.wrapping_add(invocation);
                let preceding = sender.seal(ssh_sequence, PAYLOAD, BODY_PADDING)?;
                assert_eq!(receiver.open(ssh_sequence, &preceding)?, PAYLOAD);
                packets_processed += 1;
            }
            let ssh_sequence = 0xdead_beef;
            let packet = sender.seal(ssh_sequence, PAYLOAD, BODY_PADDING)?;
            assert_eq!(
                packet,
                hex(expected),
                "{cipher} at invocation {invocation} did not match the OpenSSL bytes"
            );
            assert_eq!(&packet[..4], &[0, 0, 0, 16]);
            assert_eq!(packet.len(), 4 + 16 + 16);
            assert_eq!(receiver.open(ssh_sequence, &packet)?, PAYLOAD);
            packets_processed += 1;
        }
    }
    Ok(())
}

/// Distinct protected packets use distinct GCM nonces, even with repeated SSH
/// sequence numbers.
///
/// A one-octet counter emits the same nonce twice, which under AES-GCM leaks the
/// GHASH authentication key and permits tag forgery. This is the property the
/// carry-boundary vectors above pin numerically, asserted directly so the reason
/// is visible without recomputing a vector.
#[test]
fn gcm_nonce_advances_independently_of_ssh_sequence() -> Result<(), PacketProtectionError> {
    let iv = hex("101112131415161718191a1b");
    let key = hex("000102030405060708090a0b0c0d0e0f");
    let suite = PacketSuite::new(AES128_GCM_OPENSSH, None)?;
    let mut sender = PacketProtector::new(suite, PacketKeyMaterial::gcm(&iv, &key))?;
    let mut sealed = Vec::new();
    for invocation in 0..=257_u32 {
        let packet = sender.seal(7, PAYLOAD, BODY_PADDING)?;
        if [0, 1, 227, 228, 229, 255, 256, 257].contains(&invocation) {
            sealed.push(packet);
        }
    }
    for (index, left) in sealed.iter().enumerate() {
        for right in &sealed[index + 1..] {
            assert_ne!(
                left, right,
                "two sequence numbers produced a byte-identical packet, so the same nonce"
            );
        }
    }
    Ok(())
}

