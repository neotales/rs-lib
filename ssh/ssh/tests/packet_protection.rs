/// Every plaintext buffer a seal makes wipes itself, and the one path where the
/// bytes are still in the clear at the end of the call is `chacha20-poly1305`.
///
/// The CTR and GCM suites encrypt in place, so the clear packet they build
/// becomes the sealed packet and is handed on rather than wiped. The
/// `chacha20-poly1305` suite seals into a buffer of its own, which means its
/// clear packet is still in the clear when the function returns: a plain
/// `Vec<u8>` there would leave the whole packet, password and all, readable in
/// freed memory on every successful send over that suite.
#[test]
fn a_seal_wipes_every_plaintext_buffer_it_made() -> Result<(), Box<dyn std::error::Error>> {
    const SECRET: &[u8] = b"hunter2";

    // A record left by an earlier test on this thread would make the assertions
    // below unfalsifiable, so each lane starts from none.
    assert_eq!(take_plaintext_drop(PlaintextSlot::SealInput), None);
    assert_eq!(take_plaintext_drop(PlaintextSlot::ClearPacket), None);
    let chacha = PacketSuite::new(ENCRYPTION_CHACHA20_POLY1305_OPENSSH, None)?;
    // Not `protectors`, which derives its key and IV sizes from the suite name
    // and gets both wrong for the 64-byte key and 8-byte IV this suite takes.
    let chacha_key = [0x41_u8; 64];
    let chacha_material = || PacketKeyMaterial::new(&[0_u8; 8], &chacha_key, None);
    let mut sender = PacketProtector::new(chacha, chacha_material())?;
    let padding = chacha_padding(chacha, SECRET.len());
    let sealed = sender.seal(SEQUENCE, SECRET, &padding)?;
    assert_eq!(
        take_plaintext_drop(PlaintextSlot::ClearPacket),
        Some(PlaintextDrop::Wiped),
        "a ChaCha seal leaves its clear packet in the clear, so it must be wiped"
    );
    assert_eq!(
        take_plaintext_drop(PlaintextSlot::SealInput),
        Some(PlaintextDrop::Wiped),
        "the copy the seal worked from must be wiped"
    );
    // The bytes that went to the wire are ciphertext, so this lane also shows
    // the wipe is not applied to them.
    assert!(sealed.windows(SECRET.len()).all(|window| window != SECRET));

    for (suite, integrity) in [
        (
            PacketSuite::new(AES128_CTR, Some(HMAC_SHA2_256))?,
            AES128_CTR,
        ),
        (
            PacketSuite::new(AES128_GCM_OPENSSH, None)?,
            AES128_GCM_OPENSSH,
        ),
    ] {
        assert_eq!(take_plaintext_drop(PlaintextSlot::SealInput), None);
        assert_eq!(take_plaintext_drop(PlaintextSlot::ClearPacket), None);
        let (mut sender, mut receiver) = protectors(suite, 0x42)?;
        let padding = padding_for(suite, SECRET.len());
        let packet = sender.seal(SEQUENCE, SECRET, &padding)?;
        assert_eq!(
            receiver.open(SEQUENCE, &packet)?,
            SECRET,
            "{integrity} must still round trip"
        );
        assert_eq!(
            take_plaintext_drop(PlaintextSlot::ClearPacket),
            Some(PlaintextDrop::HandedOn),
            "{integrity} encrypts in place, so its clear packet is the sealed \
             packet and must not be wiped"
        );
        assert_eq!(
            take_plaintext_drop(PlaintextSlot::SealInput),
            Some(PlaintextDrop::Wiped),
            "{integrity}: the copy the seal worked from must be wiped"
        );
    }

    // The zlib branch replaces the caller's bytes with a compressed copy, which
    // is a different allocation on a different path. It is taken here so the
    // wipe this assertion is about is the one on that path, rather than the
    // no-compression copy the lanes above drive.
    assert_eq!(take_plaintext_drop(PlaintextSlot::SealInput), None);
    let suite = PacketSuite::new(AES256_GCM_OPENSSH, None)?;
    let zlib_key = [0x45_u8; 32];
    let mut sender = PacketProtector::new_with_compression(
        suite,
        PacketKeyMaterial::gcm(&[0x56_u8; 12], &zlib_key),
        CompressionAlgorithm::Zlib,
    )?;
    let packet = sender.seal(SEQUENCE, SECRET, &[0x11; 8])?;
    assert!(packet.windows(SECRET.len()).all(|window| window != SECRET));
    assert_eq!(
        take_plaintext_drop(PlaintextSlot::SealInput),
        Some(PlaintextDrop::Wiped),
        "the compressed copy a zlib seal works from must be wiped"
    );
    Ok(())
}

/// A seal that fails after it has taken a plaintext copy wipes that copy.
///
/// An error path is the one place a `?` releases a buffer that is still in the
/// clear. The CTR case below has already assembled the clear packet and is
/// refused by `validate_ctr_range` for an IV at the top of the range; the zlib
/// case has already compressed the payload and is refused by
/// `padding_for_payload` for an empty padding pattern.
#[test]
fn a_seal_that_fails_midway_wipes_the_plaintext_it_built() -> Result<(), Box<dyn std::error::Error>>
{
    let suite = PacketSuite::new(AES128_CTR, Some(HMAC_SHA2_256))?;
    let key = vec![0x51_u8; 16];
    let integrity_key = vec![0x52_u8; 32];
    let mut protector = PacketProtector::new(
        suite,
        PacketKeyMaterial::new(&[0xff_u8; 16], &key, Some(&integrity_key)),
    )?;
    // More than one AES block, so the range check has a second block to add to
    // a counter that is already at the top of the range. One block adds zero.
    let body = [b'p'; 40];
    let padding = padding_for(suite, body.len());

    assert_eq!(take_plaintext_drop(PlaintextSlot::ClearPacket), None);
    assert!(matches!(
        protector.seal(SEQUENCE, &body, &padding),
        Err(PacketProtectionError::CounterExhausted)
    ));
    assert_eq!(
        take_plaintext_drop(PlaintextSlot::ClearPacket),
        Some(PlaintextDrop::Wiped),
        "a failed seal must not release the clear packet it built"
    );
    assert_eq!(
        take_plaintext_drop(PlaintextSlot::SealInput),
        Some(PlaintextDrop::Wiped),
        "a failed seal must not release the copy it worked from"
    );

    // The zlib branch, where the fallible call sits *after* the payload has been
    // copied. An empty padding pattern is refused by `padding_for_payload`,
    // which runs after `compress_payload` has already produced a copy of the
    // caller's bytes: the one place a `Vec` held across a `?` would have been
    // released in the clear. The no-compression branch has no such call — its
    // framing check is inside `build_clear_packet`, downstream of the wrap.
    let suite = PacketSuite::new(AES256_GCM_OPENSSH, None)?;
    let mut protector = PacketProtector::new_with_compression(
        suite,
        PacketKeyMaterial::gcm(&[0x57_u8; 12], &[0x58_u8; 32]),
        CompressionAlgorithm::Zlib,
    )?;
    assert_eq!(take_plaintext_drop(PlaintextSlot::SealInput), None);
    assert!(matches!(
        protector.seal(SEQUENCE, PAYLOAD, &[]),
        Err(PacketProtectionError::InvalidCompression)
    ));
    assert_eq!(
        take_plaintext_drop(PlaintextSlot::SealInput),
        Some(PlaintextDrop::Wiped),
        "a zlib seal that fails after compressing must wipe the compressed copy"
    );
    Ok(())
}

/// The witness cannot be satisfied by a buffer that had nothing to destroy.
///
/// Every other wipe test would also pass against a destructor that reported a
/// wipe for a buffer it never changed, if that buffer happened to be all zeroes
/// to begin with. This drives the three cases directly, per slot: an empty
/// buffer, a non-empty all-zero buffer, and a buffer with one live byte. Only
/// the third may be reported, and the first two must leave the slot as they
/// found it.
#[test]
fn a_buffer_with_nothing_to_destroy_cannot_be_reported_as_wiped() {
    for slot in [
        PlaintextSlot::AuthRequest,
        PlaintextSlot::SealInput,
        PlaintextSlot::ClearPacket,
        PlaintextSlot::PendingPayload,
    ] {
        let _ = take_plaintext_drop(slot);
        drop(PlaintextBytes::new(slot, Vec::new()));
        assert_eq!(
            take_plaintext_drop(slot),
            None,
            "{slot:?}: an empty buffer must leave no record"
        );

        let _ = take_plaintext_drop(slot);
        drop(PlaintextBytes::new(slot, vec![0_u8; 64]));
        assert_eq!(
            take_plaintext_drop(slot),
            None,
            "{slot:?}: an all-zero buffer must not read as a wipe"
        );

        let _ = take_plaintext_drop(slot);
        let mut live = vec![0_u8; 64];
        live[17] = 0xa5;
        drop(PlaintextBytes::new(slot, live));
        assert_eq!(
            take_plaintext_drop(slot),
            Some(PlaintextDrop::Wiped),
            "{slot:?}: a buffer with a live byte must report the wipe"
        );

        // The last case is the one the other tests depend on, so it is stated
        // here as well: a buffer whose wipe is skipped has to be distinguishable
        // from one that was wiped, not merely absent.
        let _ = take_plaintext_drop(slot);
        let mut unwiped = PlaintextBytes::new(slot, vec![0_u8; 64]);
        unwiped.as_mut_slice()[17] = 0xa5;
        std::mem::forget(unwiped);
        assert_eq!(
            take_plaintext_drop(slot),
            None,
            "{slot:?}: a leaked buffer must leave no record rather than a wipe"
        );
    }
}

fn protectors(
    suite: PacketSuite,
    seed: u8,
) -> Result<(PacketProtector, PacketProtector), PacketProtectionError> {
    Ok((
        PacketProtector::new(suite, material_for(suite, seed))?,
        PacketProtector::new(suite, material_for(suite, seed))?,
    ))
}

fn material_for(suite: PacketSuite, seed: u8) -> PacketKeyMaterial {
    let key_size = if suite.encryption_name().contains("256") {
        32
    } else {
        16
    };
    let iv_size = if suite.integrity_name().is_none() {
        12
    } else {
        16
    };
    let key = vec![seed; key_size];
    let iv = vec![seed.wrapping_add(1); iv_size];
    let integrity = suite.integrity_name().map(|name| {
        let size = if name.contains("sha2-512") { 64 } else { 32 };
        vec![seed.wrapping_add(2); size]
    });
    PacketKeyMaterial::new(&iv, &key, integrity.as_deref())
}

/// Padding for one payload, taken from the crate's own alignment rule.
///
/// These used to be copies of the arithmetic, one of them keyed off the
/// integrity name string and another keyed off a bare `body_is_aligned` flag.
/// A copy is not a derivation: it agrees with itself and disagrees with the
/// code the moment either one changes.
fn chacha_padding(suite: PacketSuite, payload_size: usize) -> Vec<u8> {
    vec![0xa5; padding_length(suite, payload_size)]
}

fn padding_for(suite: PacketSuite, payload_size: usize) -> Vec<u8> {
    vec![0xa5; padding_length(suite, payload_size)]
}

fn padding_length(suite: PacketSuite, payload_size: usize) -> usize {
    PacketAlignment::for_suite(suite)
        .padding_length(payload_size)
        .expect("alignment rule must produce a padding length")
}

/// The block-alignment rule, pinned per suite against OpenSSH's source.
///
/// The two numbers per case come from OpenSSH 10.5p1. `block_size` is the
/// second field of `static const struct sshcipher ciphers[]` in `cipher.c`
/// (field order `name, block_size, key_len, iv_len, auth_len, flags`), copied
/// into the key context by `kex.c` line 821,
/// `enc->block_size = cipher_blocksize(enc->cipher);`:
///
/// ```text
/// { "aes128-gcm@openssh.com",       16, 16, 12, 16, 0, EVP_aes_128_gcm },
/// { "chacha20-poly1305@openssh.com", 8, 64, 0, 16, CFLAG_CHACHAPOLY, NULL },
/// ```
///
/// `aligns_packet_length` is OpenSSH's `aadlen != 0` case, from `packet.c` line
/// 1244 -- `aadlen = (mac && mac->enabled && mac->etm) || authlen ? 4 : 0` --
/// read back on the receive side at `packet.c` lines 1702-1711, where
/// `need = state->packlen` when `aadlen` is set and
/// `need = 4 + state->packlen - block_size` when it is not, and the packet is
/// rejected unless `need % block_size == 0`.
///
/// Pinning it as a table means a later change to the rule has to change this
/// test too. That is the whole reason the rule is a function of
/// `(suite, payload_len)` and not four separate pieces of arithmetic.
#[test]
fn block_alignment_is_pinned_per_suite_against_openssh() -> Result<(), PacketProtectionError> {
    let cases: [(&str, PacketSuite, usize, bool); 7] = [
        (
            "chacha20-poly1305@openssh.com",
            PacketSuite::new(ENCRYPTION_CHACHA20_POLY1305_OPENSSH, None)?,
            8,
            true,
        ),
        (
            "aes128-gcm@openssh.com",
            PacketSuite::new(AES128_GCM_OPENSSH, None)?,
            16,
            true,
        ),
        (
            "aes256-gcm@openssh.com",
            PacketSuite::new(AES256_GCM_OPENSSH, None)?,
            16,
            true,
        ),
        (
            "aes128-ctr + hmac-sha2-256-etm@openssh.com",
            PacketSuite::new(AES128_CTR, Some(HMAC_SHA2_256_ETM_OPENSSH))?,
            16,
            true,
        ),
        (
            "aes256-ctr + hmac-sha2-512-etm@openssh.com",
            PacketSuite::new(AES256_CTR, Some(HMAC_SHA2_512_ETM_OPENSSH))?,
            16,
            true,
        ),
        (
            "aes128-ctr + hmac-sha2-256",
            PacketSuite::new(AES128_CTR, Some(HMAC_SHA2_256))?,
            16,
            false,
        ),
        (
            "aes256-ctr + hmac-sha2-512",
            PacketSuite::new(AES256_CTR, Some(HMAC_SHA2_512))?,
            16,
            false,
        ),
    ];

    for (name, suite, block_size, aligns_packet_length) in cases {
        let alignment = PacketAlignment::for_suite(suite);
        assert_eq!(alignment.block_size(), block_size, "block size for {name}");
        assert_eq!(
            alignment.aligns_packet_length(),
            aligns_packet_length,
            "which length is aligned, for {name}"
        );
        assert_eq!(
            alignment.header_length(),
            if aligns_packet_length { 1 } else { 5 },
            "framing header counted in the alignment, for {name}"
        );

        for payload_length in 0..96_usize {
            let packet_length = aligned_packet_length(&alignment, payload_length, name)?;
            let aligned = if aligns_packet_length {
                packet_length
            } else {
                4 + packet_length
            };
            assert_eq!(
                aligned % block_size,
                0,
                "{name} does not land on its block boundary"
            );
            // The padding is also the smallest legal one, which is what makes
            // the rule a bijection rather than merely a valid choice.
            let shorter = alignment.padding_length(payload_length)? - 4;
            if shorter >= 4 {
                let shorter_packet_length = 1 + payload_length + shorter;
                assert!(
                    alignment
                        .validate_packet_length(shorter_packet_length)
                        .is_err(),
                    "{name} must not leave a shorter legal padding for {payload_length}"
                );
            }
        }
    }
    Ok(())
}

/// The `packet_length` the rule produces for one payload, checked against it.
fn aligned_packet_length(
    alignment: &PacketAlignment,
    payload_length: usize,
    name: &str,
) -> Result<usize, PacketProtectionError> {
    let padding = alignment.padding_length(payload_length)?;
    assert!(padding >= 4, "OpenSSH requires at least four, for {name}");
    let packet_length = 1_usize
        .checked_add(payload_length)
        .and_then(|size| size.checked_add(padding))
        .ok_or(PacketProtectionError::LimitExceeded)?;
    alignment
        .validate_packet_length(packet_length)
        .map_err(|_error| PacketProtectionError::InvalidAlignment)?;
    Ok(packet_length)
}

/// The two suites that are not negotiated: the pre-NEWKEYS stream, and the rule
/// reached from its halves rather than from a suite.
#[test]
fn unprotected_and_explicit_alignments_follow_the_same_rule() -> Result<(), PacketProtectionError> {
    // The pre-NEWKEYS stream is the same rule with no key context: `packet.c`
    // line 1243 falls back to `block_size = 8` and line 1244 leaves `aadlen` at
    // zero, so it is the encrypt-and-MAC branch on an eight-byte block.
    let unprotected = PacketAlignment::UNPROTECTED;
    assert_eq!(unprotected.block_size(), 8);
    assert!(!unprotected.aligns_packet_length());
    assert_eq!(unprotected.header_length(), 5);
    // `packet_length` is `1 + payload + padding` and `4 + packet_length` must
    // be a multiple of eight, with at least four bytes of padding.
    assert_eq!(unprotected.padding_length(0)?, 11);
    assert_eq!(unprotected.padding_length(1)?, 10);
    assert_eq!(unprotected.padding_length(2)?, 9);
    assert_eq!(unprotected.padding_length(3)?, 8);
    assert_eq!(
        unprotected.padding_pattern(2, &[0xa5, 0x5a])?,
        vec![0xa5, 0x5a, 0xa5, 0x5a, 0xa5, 0x5a, 0xa5, 0x5a, 0xa5]
    );
    assert_eq!(
        unprotected.padding_pattern(2, &[]),
        Err(AlignmentError::EmptyPattern)
    );

    // `new` is the same rule from its two halves, which is how the public
    // `compression::padding_for_payload` reaches it.
    for block_size in [8_usize, 16] {
        for aligns_packet_length in [true, false] {
            let alignment = PacketAlignment::new(block_size, aligns_packet_length);
            let packet_length = 8 + alignment.padding_length(7)?;
            alignment.validate_packet_length(packet_length)?;
            let aligned = if aligns_packet_length {
                packet_length
            } else {
                4 + packet_length
            };
            assert_eq!(aligned % block_size, 0);
        }
    }
    assert_eq!(PacketAlignment::new(16, false).header_length(), 5);
    assert_eq!(PacketAlignment::new(16, true).header_length(), 1);
    Ok(())
}

fn authenticated_eam_packet(
    key: &[u8; 16],
    iv: &[u8; 16],
    mac_key: &[u8; 32],
    sequence: u32,
    body: &[u8],
) -> Vec<u8> {
    let length = u32::try_from(body.len()).expect("test body fits a packet length");
    authenticated_eam_packet_with_length(key, iv, mac_key, sequence, length, body)
}

fn authenticated_eam_packet_with_length(
    key: &[u8; 16],
    iv: &[u8; 16],
    mac_key: &[u8; 32],
    sequence: u32,
    packet_length: u32,
    body: &[u8],
) -> Vec<u8> {
    let mut clear = Vec::with_capacity(4 + body.len() + 32);
    clear.extend_from_slice(&packet_length.to_be_bytes());
    clear.extend_from_slice(body);
    let mut mac = <hmac::Hmac<sha2::Sha256> as hmac::KeyInit>::new_from_slice(mac_key)
        .expect("test HMAC key is valid");
    mac.update(&sequence.to_be_bytes());
    mac.update(&clear);
    let tag = mac.finalize();
    let mut stream = ctr::Ctr128BE::<aes::Aes128>::new_from_slices(key, iv)
        .expect("test CTR key and IV are valid");
    stream.apply_keystream(&mut clear);
    clear.extend_from_slice(tag.as_bytes());
    clear
}

fn hex(value: &str) -> Vec<u8> {
    assert_eq!(value.len() % 2, 0, "hex input must have even length");
    value
        .as_bytes()
        .as_chunks::<2>()
        .0
        .iter()
        .map(|pair| {
            let text = std::str::from_utf8(pair).expect("hex input must be ASCII");
            u8::from_str_radix(text, 16).expect("hex input must be hexadecimal")
        })
        .collect()
}
