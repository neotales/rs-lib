#[test]
fn ctr_state_continues_and_rekey_is_the_only_explicit_reset() -> Result<(), PacketProtectionError> {
    let suite = PacketSuite::new(AES128_CTR, Some(HMAC_SHA2_256_ETM_OPENSSH))?;
    let (mut sender, mut receiver) = protectors(suite, 0x42)?;
    let padding = padding_for(suite, PAYLOAD.len());
    let first = sender.seal(3, PAYLOAD, &padding)?;
    let second = sender.seal(4, PAYLOAD, &padding)?;
    let mut fresh_sender = PacketProtector::new(suite, material_for(suite, 0x42))?;
    let mut fresh_receiver = PacketProtector::new(suite, material_for(suite, 0x42))?;
    let fresh_first = fresh_sender.seal(3, PAYLOAD, &padding)?;
    assert_eq!(first, fresh_first);
    assert_eq!(receiver.open(3, &first)?, PAYLOAD);
    assert_eq!(receiver.open(4, &second)?, PAYLOAD);
    assert_eq!(fresh_receiver.open(3, &fresh_first)?, PAYLOAD);

    let mut same_sequence_sender = PacketProtector::new(suite, material_for(suite, 0x43))?;
    let mut same_sequence_receiver = PacketProtector::new(suite, material_for(suite, 0x43))?;
    let repeated_a = same_sequence_sender.seal(9, PAYLOAD, &padding)?;
    let repeated_b = same_sequence_sender.seal(9, PAYLOAD, &padding)?;
    assert_ne!(repeated_a, repeated_b);
    assert_eq!(same_sequence_receiver.open(9, &repeated_a)?, PAYLOAD);
    assert_eq!(same_sequence_receiver.open(9, &repeated_b)?, PAYLOAD);

    let new_suite = PacketSuite::new(AES256_CTR, Some(HMAC_SHA2_256))?;
    sender.rekey(new_suite, material_for(new_suite, 0x44))?;
    receiver.rekey(new_suite, material_for(new_suite, 0x44))?;
    assert_eq!(sender.suite(), new_suite);
    assert!(receiver.open(5, &first).is_err());
    let rekeyed = sender.seal(5, PAYLOAD, &[0x31; 4])?;
    assert_eq!(receiver.open(5, &rekeyed)?, PAYLOAD);
    Ok(())
}

