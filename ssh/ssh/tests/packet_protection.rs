fn every_ctr_and_etm_variant_round_trips_multiple_lengths() -> Result<(), PacketProtectionError> {
    let variants = [
        (AES128_CTR, HMAC_SHA2_256),
        (AES256_CTR, HMAC_SHA2_256),
        (AES256_CTR, HMAC_SHA2_512),
        (AES128_CTR, HMAC_SHA2_256_ETM_OPENSSH),
        (AES256_CTR, HMAC_SHA2_256_ETM_OPENSSH),
        (AES256_CTR, HMAC_SHA2_512_ETM_OPENSSH),
    ];
    let payloads: [&[u8]; 5] = [b"", b"x", PAYLOAD, &[0x55; 16], &[0x66; 31]];

    for (variant, (cipher, integrity)) in variants.into_iter().enumerate() {
        let suite = PacketSuite::new(cipher, Some(integrity))?;
        let seed = u8::try_from(variant).map_err(|_error| PacketProtectionError::InvalidPacket)?;
        let (mut sender, mut receiver) = protectors(suite, seed)?;
        for (sequence, payload) in payloads.into_iter().enumerate() {
            let sequence =
                u32::try_from(sequence).map_err(|_error| PacketProtectionError::InvalidPacket)?;
            let padding = padding_for(suite, payload.len());
            let packet = sender.seal(sequence, payload, &padding)?;
            assert_eq!(receiver.open(sequence, &packet)?, payload);
        }
    }
    Ok(())
}

