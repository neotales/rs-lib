/// PROVENANCE of the values asserted here: **generated by this crate**.
///
/// The numbers below are the crate's own `C_INIT_LENGTH`, the crate's own
/// `as_bytes().len()`, and so on. Nothing here was read out of OpenSSH, so the
/// "openssh" in this test's name describes where the *lengths come from*, not
/// where these bytes came from.
///
/// The lengths themselves are not arbitrary, and that is the part worth checking,
/// so it is spelled out rather than left to the constant names. The hybrid
/// construction fixed by draft-ietf-sshm-mlkem768x25519-sha256 concatenates an
/// ML-KEM-768 encapsulation key with an X25519 public value, and the crate's
/// constants are the arithmetic of that, from FIPS 203's parameter sizes:
///
/// ```text
/// MLKEM768_PUBLIC_KEY_LENGTH = 1184   (FIPS 203, ML-KEM-768 ek)
/// MLKEM768_CIPHERTEXT_LENGTH = 1088   (FIPS 203, ML-KEM-768 ct)
/// X25519_PUBLIC_KEY_LENGTH   =   32   (RFC 7748)
/// C_INIT_LENGTH = 1184 + 32  = 1216
/// S_REPLY_LENGTH = 1088 + 32 = 1120
/// ```
///
/// So the two lengths are pinned to the primitive sizes they are built from. What
/// this test cannot do is confirm the *framing* against OpenSSH: the assertions
/// compare this crate against itself. The test that does compare against real
/// implementations is `tests/mlkem_vector.rs`, which pins a captured Go client
/// and OpenSSH 9.9 transcript, and `tests/openssh_interop.rs`, which runs a live
/// `sshd`.
#[test]
fn hybrid_exchange_uses_fixed_openssh_value_lengths_and_string_framed_secret()
-> Result<(), Box<dyn std::error::Error>> {
    let mut client_kexinit = msg::kexinit::KexInit::client_defaults([0x11; 16]);
    let mut server_kexinit = msg::kexinit::KexInit::server_defaults([0x22; 16]);
    client_kexinit.kex_algorithms = vec![KEX_MLKEM768X25519_SHA256.to_owned()];
    server_kexinit.kex_algorithms = vec![KEX_MLKEM768X25519_SHA256.to_owned()];
    let context = KexContext::new(
        "SSH-2.0-fixed-client",
        "SSH-2.0-fixed-server",
        client_kexinit.encode()?,
        server_kexinit.encode()?,
        KEX_MLKEM768X25519_SHA256,
    )?;
    let client = ClientKex::from_seeds(&[0x31; 64], &[0x32; 32]);
    assert_eq!(client.client_init().len(), C_INIT_LENGTH);

    let mut server = ServerKex::new(context.clone(), b"host-key-blob")?;
    let prepared = server.accept_init(&client.init_message()?)?;
    let reply = prepared.reply_message(b"signature-blob")?;
    let completion = client.complete(&context, &reply)?;

    assert_eq!(completion.exchange_hash, *prepared.exchange_hash());
    assert_eq!(completion.session_id, completion.exchange_hash);
    // 32 = 32 bytes of X25519 output, with a leading zero because the top bit is
    // set, so the mpint is 33 bytes and the string is 4 + 33.
    assert_eq!(completion.shared_secret.as_bytes()[..4], [0, 0, 0, 32]);
    assert_eq!(completion.shared_secret.as_bytes().len(), 36);
    assert_eq!(completion.host_key_blob, b"host-key-blob");
    assert_eq!(completion.signature_blob, b"signature-blob");

    let mut encoded = Writer::new();
    encoded.write_string(completion.shared_secret.as_bytes())?;
    assert_eq!(encoded.into_bytes().len(), 40);
    Ok(())
}

/// PROVENANCE: **generated by this crate**, on the same terms as the test above.
/// The layout is parsed out of a reply this crate built, and the ciphertext
/// length is checked against the crate's own `S_REPLY_LENGTH`. The test name
/// says "openssh" because the layout is the one OpenSSH implements; the bytes
/// being parsed did not come from OpenSSH.
#[test]
fn server_reply_has_the_openssh_ciphertext_and_x25519_layout()
-> Result<(), Box<dyn std::error::Error>> {
    let mut client_kexinit = msg::kexinit::KexInit::client_defaults([0x11; 16]);
    let mut server_kexinit = msg::kexinit::KexInit::server_defaults([0x22; 16]);
    client_kexinit.kex_algorithms = vec![KEX_MLKEM768X25519_SHA256.to_owned()];
    server_kexinit.kex_algorithms = vec![KEX_MLKEM768X25519_SHA256.to_owned()];
    let context = KexContext::new(
        "SSH-2.0-fixed-client",
        "SSH-2.0-fixed-server",
        client_kexinit.encode()?,
        server_kexinit.encode()?,
        KEX_MLKEM768X25519_SHA256,
    )?;
    let client = ClientKex::from_seeds(&[0x41; 64], &[0x42; 32]);
    let mut server = ServerKex::new(context, b"host-key-blob")?;
    let prepared = server.accept_init(&client.init_message()?)?;
    let reply = prepared.reply_message(b"signature-blob")?;
    let mut reader = neotales_ssh::Reader::new(&reply);
    assert_eq!(reader.read_byte()?, 31);
    assert_eq!(reader.read_string()?, b"host-key-blob");
    assert_eq!(reader.read_string()?.len(), S_REPLY_LENGTH);
    assert_eq!(reader.read_string()?, b"signature-blob");
    assert!(reader.is_empty());
    Ok(())
}

#[test]
fn role_lengths_constructor_and_one_shot_state_are_enforced()
-> Result<(), Box<dyn std::error::Error>> {
    let mut client_kexinit = msg::kexinit::KexInit::client_defaults([0x11; 16]);
    let mut server_kexinit = msg::kexinit::KexInit::server_defaults([0x22; 16]);
    client_kexinit.kex_algorithms = vec![KEX_MLKEM768X25519_SHA256.to_owned()];
    server_kexinit.kex_algorithms = vec![KEX_MLKEM768X25519_SHA256.to_owned()];
    let context = KexContext::new(
        "SSH-2.0-fixed-client",
        "SSH-2.0-fixed-server",
        client_kexinit.encode()?,
        server_kexinit.encode()?,
        KEX_MLKEM768X25519_SHA256,
    )?;
    let client = ClientKex::from_seeds(&[0x51; 64], &[0x52; 32]);
    let client_message = client.init_message()?;
    assert_eq!(
        validate_client_public_blob(&[0; S_REPLY_LENGTH]),
        Err(KexError::InvalidPublicKey)
    );
    assert_eq!(
        validate_server_public_blob(&[0; C_INIT_LENGTH]),
        Err(KexError::InvalidPublicKey)
    );
    assert!(matches!(
        ServerKex::new(context.clone(), b""),
        Err(KexError::InvalidFieldLength)
    ));
    let mut server = ServerKex::new(context, b"host-key-blob")?;
    assert!(server.accept_init(&client_message).is_ok());
    assert!(matches!(
        server.accept_init(&client_message),
        Err(KexError::InvalidState)
    ));
    Ok(())
}

#[test]
fn malformed_and_low_order_client_values_fail_closed() -> Result<(), Box<dyn std::error::Error>> {
    let mut client_kexinit = msg::kexinit::KexInit::client_defaults([0x11; 16]);
    let mut server_kexinit = msg::kexinit::KexInit::server_defaults([0x22; 16]);
    client_kexinit.kex_algorithms = vec![KEX_MLKEM768X25519_SHA256.to_owned()];
    server_kexinit.kex_algorithms = vec![KEX_MLKEM768X25519_SHA256.to_owned()];
    let context = KexContext::new(
        "SSH-2.0-fixed-client",
        "SSH-2.0-fixed-server",
        client_kexinit.encode()?,
        server_kexinit.encode()?,
        KEX_MLKEM768X25519_SHA256,
    )?;
    let client = ClientKex::from_seeds(&[0x61; 64], &[0x62; 32]);
    let message = client.init_message()?;
    let mut reader = neotales_ssh::Reader::new(&message);
    assert_eq!(reader.read_byte()?, 30);
    let mut value = reader.read_string()?.to_vec();
    value[MLKEM768_PUBLIC_KEY_LENGTH..].fill(0);
    let mut malformed = Writer::new();
    malformed.write_byte(30);
    malformed.write_string(&value)?;
    let mut server = ServerKex::new(context, b"host-key-blob")?;
    assert!(matches!(
        server.accept_init(&malformed.into_bytes()),
        Err(KexError::NonContributorySecret)
    ));

    let client = ClientKex::from_seeds(&[0x71; 64], &[0x72; 32]);
    let mut server = ServerKex::new(
        KexContext::new(
            "SSH-2.0-fixed-client",
            "SSH-2.0-fixed-server",
            client_kexinit.encode()?,
            server_kexinit.encode()?,
            KEX_MLKEM768X25519_SHA256,
        )?,
        b"host-key-blob",
    )?;
    let mut wrong_type = client.init_message()?;
    wrong_type[0] = 31;
    assert!(matches!(
        server.accept_init(&wrong_type),
        Err(KexError::InvalidMessageType)
    ));
    Ok(())
}
