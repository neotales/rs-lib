//! The validity window, at the years where RFC 5280 changes the encoding.
//!
//! An X.509 validity field is a `UTCTime` or a `GeneralizedTime`, and RFC 5280
//! §4.1.2.5 says which: a two-digit year in `UTCTime` for 1950 through 2049, a
//! four-digit year in `GeneralizedTime` for 2050 and later, and a
//! `GeneralizedTime` for anything before 1950 because a two-digit year cannot
//! name it. All three therefore have to be readable, and a parser that reads
//! only the short form rejects a 25-year CA certificate issued in 2025.
//!
//! This file is the pinned evidence for that, in both directions.
//!
//! | fixture | encoding | why it is here |
//! |---|---|---|
//! | `validity-1949.der` | `GeneralizedTime` twice | before the `UTCTime` window |
//! | `validity-1950.der` | `UTCTime` twice | first year of the `UTCTime` window |
//! | `validity-2045.der` | `UTCTime` twice | the control: the path that already worked |
//! | `validity-2049.der` | `UTCTime` twice | last year of the `UTCTime` window |
//! | `validity-2050.der` | `GeneralizedTime` twice | first year the long form is required for |
//! | `validity-not-after-2136.der` | `UTCTime`, then `GeneralizedTime` | a 110-year certificate, each field a different encoding |
//! | `validity-not-before-1949.der` | `GeneralizedTime` twice | a pre-1950 `notBefore` |
//!
//! Every fixture is checked for the encoding the reference tool actually chose
//! before the conversion is attempted, so a fixture regenerated wrongly fails
//! here rather than quietly ceasing to cover the case it is named for.
//!
//! # Where a fixture cannot succeed
//!
//! The 1949 and 1950 cases are *rejected*, and that is not the bug this file is
//! about. An OpenSSH certificate's `valid_after` and `valid_before` are `u64`
//! seconds since the Unix epoch, so a validity date before 1970 has no
//! representation and there is nothing to convert it to. Their years are read
//! correctly now, and the difference between "the year was unreadable" and "the
//! instant is out of range" is asserted in the unit tests in
//! `src/openssh_cert.rs`, which are the only place that can see it — the public
//! error is one variant. Anything that wants a pre-1970 date to convert is
//! asking for a change to the SSH wire format, not to this parser.
//!
//! # The fixtures
//!
//! Seven DER certificates generated by the reference implementation, **OpenSSL
//! 3.6.3**, and committed so that the suite needs neither a network nor a local
//! `openssl`. The recipe, the exact command per fixture and the reason each one
//! exists are in [`fixtures/README.md`](../tests/fixtures/README.md); the
//! short form is:
//!
//! ```text
//! openssl genpkey -algorithm ed25519 -out k.pem
//! openssl req -new -x509 -key k.pem -out c.der -outform DER \
//!     -not_before 20500928000000Z -not_after 20501127000000Z \
//!     -subj /CN=validity-2050.example -set_serial 7
//! ```
//!
//! `openssl req -x509` takes `-not_before` and `-not_after` as
//! `CCYYMMDDHHMMSSZ` or `YYMMDDHHMMSSZ` and picks `UTCTime` or
//! `GeneralizedTime` itself, which is the point: the encoding under test is the
//! one the reference tool chose, not one this repository asked for. A fixture
//! generated by the crate under test would only prove the crate is
//! self-consistent.
//!
//! The reject cases are *not* fixtures. No reference tool will emit a
//! `GeneralizedTime` whose year is `20x5`, so those certificates are assembled
//! here, byte by byte, and the claim they support is narrower: whatever the
//! reason, a malformed validity field is a typed error and never an acceptance.

// `missing_docs` is a workspace lint aimed at the published API. A test binary
// has no public API to document, so the lint firing here is noise rather than a
// finding. Scoped to this file, so an undocumented public item in the crate is
// still reported.
#![allow(missing_docs)]

use neotales_x509::{
    OpenSshCertError,
    openssh_cert::{self, OpenSshCertKind, OpenSshCertRequest},
};

/// The one conversion request every case shares, so a difference in the result
/// is a difference in the validity window and nothing else.
fn request() -> OpenSshCertRequest {
    OpenSshCertRequest {
        kind: OpenSshCertKind::Host,
        serial: 7,
        key_id: "validity".to_owned(),
        principals: vec!["server.example".to_owned()],
        nonce: vec![9, 9],
        critical_options: Vec::new(),
        extensions: Vec::new(),
    }
}

/// A fixed 32-byte authority seed, so every conversion signs the same way.
fn seed() -> [u8; 32] {
    std::array::from_fn(|index| u8::try_from(index).expect("seed offset is small"))
}

/// Converts a certificate and reads back the validity window it carried.
///
/// The conversion is the only way a caller learns the window: the X.509 times
/// become the OpenSSH `valid_after` and `valid_before`. The certificate is
/// parsed back rather than trusted, because a conversion that produced an
/// unreadable certificate would otherwise be reported as a success.
fn validity_window(der: &[u8]) -> Result<(u64, u64), OpenSshCertError> {
    let blob = openssh_cert::x509_to_openssh_certificate(der, &request(), &seed())?;
    let certificate = openssh_cert::parse(&blob).expect("a certificate this crate signed parses");
    Ok((certificate.valid_after, certificate.valid_before))
}

/// One ASN.1 time, as the bytes carry it rather than as the parser reads it.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct Time<'a> {
    /// Whether the field is a `GeneralizedTime` rather than a `UTCTime`.
    generalized: bool,
    /// The content octets, digits and the trailing `Z`.
    content: &'a str,
}

impl Time<'_> {
    const fn tag(self) -> u8 {
        if self.generalized { 0x18 } else { 0x17 }
    }

    const fn length(self) -> usize {
        if self.generalized { 15 } else { 13 }
    }
}

/// Every ASN.1 time a certificate carries, in the order the bytes hold them.
///
/// This is a scan rather than a parse on purpose: the test wants to know what
/// the reference tool wrote, and it must not borrow the code under test to
/// answer. A tag byte, the short-form length that tag can only have, and
/// nothing but digits and a `Z` is a shape nothing else in these certificates
/// has, so a match is a time and a non-match is not.
fn time_encodings(der: &[u8]) -> Vec<Time<'_>> {
    let mut found = Vec::new();
    for index in 0..der.len() {
        for generalized in [false, true] {
            let candidate = Time {
                generalized,
                content: "",
            };
            let length = candidate.length();
            let tag = candidate.tag();
            let Some(content) = der.get(index + 2..index + 2 + length) else {
                continue;
            };
            if der.get(index) != Some(&tag)
                || der.get(index + 1) != Some(&u8::try_from(length).expect("length is short-form"))
                || content.last() != Some(&b'Z')
                || !content[..length - 1].iter().all(u8::is_ascii_digit)
            {
                continue;
            }
            found.push(Time {
                generalized,
                content: std::str::from_utf8(content).expect("the shape check proved ASCII"),
            });
        }
    }
    found
}

/// A `UTCTime` the reference tool wrote.
const fn utc(content: &'static str) -> Time<'static> {
    Time {
        generalized: false,
        content,
    }
}

/// A `GeneralizedTime` the reference tool wrote.
const fn generalized(content: &'static str) -> Time<'static> {
    Time {
        generalized: true,
        content,
    }
}

/// One row of the boundary table: a fixture, the encoding the reference tool
/// chose for it, and what converting it has to produce.
struct Boundary {
    /// What to call the case in a failure message.
    name: &'static str,
    /// The committed fixture.
    der: &'static [u8],
    /// The two times, in the order the bytes hold them.
    encodings: &'static [Time<'static>],
    /// The validity window the conversion has to produce, or the error it has to
    /// refuse with.
    expected: Result<(u64, u64), OpenSshCertError>,
}

/// The years either side of the encoding change, and the 2045 path that already
/// worked.
///
/// Every expected timestamp is written out rather than computed, so a change in
/// the calendar arithmetic cannot quietly redefine what a fixture means. The two
/// rejections are the pre-epoch cases described in the module documentation; the
/// four successes are the years on each side of 2050.
const BOUNDARIES: [Boundary; 7] = [
    Boundary {
        name: "1949",
        der: include_bytes!("fixtures/validity-1949.der").as_slice(),
        encodings: &[
            generalized("19490928000000Z"),
            generalized("19491127000000Z"),
        ],
        expected: Err(OpenSshCertError::InvalidTime),
    },
    Boundary {
        name: "1950",
        der: include_bytes!("fixtures/validity-1950.der").as_slice(),
        encodings: &[utc("500928000000Z"), utc("501127000000Z")],
        expected: Err(OpenSshCertError::InvalidTime),
    },
    Boundary {
        name: "2045",
        der: include_bytes!("fixtures/validity-2045.der").as_slice(),
        encodings: &[utc("450928000000Z"), utc("451127000000Z")],
        expected: Ok((2_390_169_600, 2_395_353_600)),
    },
    Boundary {
        name: "2049",
        der: include_bytes!("fixtures/validity-2049.der").as_slice(),
        encodings: &[utc("490928000000Z"), utc("491127000000Z")],
        expected: Ok((2_516_400_000, 2_521_584_000)),
    },
    Boundary {
        name: "2050",
        der: include_bytes!("fixtures/validity-2050.der").as_slice(),
        encodings: &[
            generalized("20500928000000Z"),
            generalized("20501127000000Z"),
        ],
        expected: Ok((2_547_936_000, 2_553_120_000)),
    },
    Boundary {
        name: "notAfter 2136",
        der: include_bytes!("fixtures/validity-not-after-2136.der").as_slice(),
        encodings: &[utc("260928000000Z"), generalized("21361127000000Z")],
        expected: Ok((1_790_553_600, 5_267_030_400)),
    },
    Boundary {
        name: "notBefore 1949",
        der: include_bytes!("fixtures/validity-not-before-1949.der").as_slice(),
        encodings: &[
            generalized("19490928000000Z"),
            generalized("21361127000000Z"),
        ],
        expected: Err(OpenSshCertError::InvalidTime),
    },
];

/// The year a time names, with a `UTCTime`'s two digits expanded through the
/// 1950 pivot.
///
/// This repeats the parser's own rule on purpose: the claim under test here is
/// which *years* the table reaches and which *encoding* the reference tool chose
/// for each, not the calendar arithmetic, which the pinned timestamps in
/// [`BOUNDARIES`] assert directly.
fn year_of(time: &Time<'_>) -> Option<u32> {
    let digits = time.content.get(..if time.generalized { 4 } else { 2 })?;
    let year: u32 = digits.parse().ok()?;
    if time.generalized {
        Some(year)
    } else if year <= 49 {
        Some(2000 + year)
    } else {
        Some(1900 + year)
    }
}

/// The table is the coverage claim, so it is asserted rather than trusted: the
/// years on both sides of the change, the control that already worked, and one
/// certificate with a field of each encoding.
#[test]
fn the_boundary_table_covers_both_sides_of_the_encoding_change() {
    let years: std::collections::BTreeSet<u32> = BOUNDARIES
        .iter()
        .flat_map(|boundary| boundary.encodings.iter())
        .filter_map(year_of)
        .collect();
    for year in [1949, 1950, 2026, 2045, 2049, 2050, 2136] {
        assert!(
            years.contains(&year),
            "{year} is a year the table has to cover, and the years it covers are {years:?}"
        );
    }
    let mixed = BOUNDARIES
        .iter()
        .filter(|boundary| {
            boundary.encodings.iter().any(|time| time.generalized)
                && boundary.encodings.iter().any(|time| !time.generalized)
        })
        .count();
    assert_eq!(mixed, 1, "one certificate carries an encoding of each kind");
}

/// Each fixture converts, or is refused, exactly as RFC 5280 and the OpenSSH
/// wire format require.
#[test]
fn the_years_where_the_encoding_changes_convert_as_rfc_5280_requires() {
    for boundary in &BOUNDARIES {
        assert_eq!(
            time_encodings(boundary.der),
            boundary.encodings,
            "{}: the encoding the reference tool chose is the case under test",
            boundary.name
        );
        assert_eq!(
            validity_window(boundary.der),
            boundary.expected,
            "{}",
            boundary.name
        );
    }
}

/// The two fields are read independently, so a long-form `notAfter` beside a
/// short-form `notBefore` is the ordinary case rather than an exotic one.
///
/// The 2045 fixture in `truncation_sweep` is the same shape, and its sweep
/// still passes: the fix adds a branch that reads, and changes nothing about the
/// branch that already did.
#[test]
fn a_short_and_a_long_encoding_coexist_in_one_certificate() {
    let der = include_bytes!("fixtures/validity-not-after-2136.der").as_slice();
    let encodings = time_encodings(der);
    assert_eq!(
        encodings.iter().filter(|time| time.generalized).count(),
        1,
        "one field is long-form and one is short-form"
    );
    // 2026-09-28 and 2136-11-27, both at midnight Zulu.
    assert_eq!(validity_window(der), Ok((1_790_553_600, 5_267_030_400)));
    // The far end of the window is a plain `u64`, so a 110-year certificate is
    // a large number rather than a special case.
    let (_, valid_before) = validity_window(der).expect("the 2136 certificate converts");
    assert!(
        valid_before > 1_u64 << 32,
        "the year 2136 is past 2^32 seconds"
    );
}

/// A validity field no reference tool would write is a typed error, in either
/// position, and is never accepted.
///
/// The other half of the claim is in the unit tests in `src/openssh_cert.rs`:
/// these assert that the error is typed, and those assert which of the two
/// fields it came from and why, which the single public variant cannot express.
#[test]
fn a_malformed_validity_field_is_a_typed_error_in_either_position() {
    // The controls, from the same builder: two fields of the short form, and one
    // of each form, both convert. Without them every row below could fail for a
    // reason that has nothing to do with the field it puts in the certificate.
    for (before, after, expected) in [
        (
            (0x17u8, &b"260928000000Z"[..]),
            (0x17, &b"451127000000Z"[..]),
            Ok((1_790_553_600, 2_395_353_600)),
        ),
        (
            (0x17, &b"260928000000Z"[..]),
            (0x18, &b"20501127000000Z"[..]),
            Ok((1_790_553_600, 2_553_120_000)),
        ),
    ] {
        assert_eq!(
            validity_window(&certificate_with_times(before, after)),
            expected,
            "the builder's control converts"
        );
    }

    for (name, tag, content) in [
        ("a non-decimal year", 0x18u8, &b"20x61127000000Z"[..]),
        ("a five-digit year", 0x18, &b"99999999999999Z"[..]),
        ("an empty field", 0x18, &b""[..]),
        ("a short field", 0x18, &b"2136112700000Z"[..]),
        ("a field without Zulu", 0x18, &b"21361127000000X"[..]),
        ("30 February", 0x18, &b"20500230000000Z"[..]),
        ("an hour of 24", 0x18, &b"20502400000000Z"[..]),
        ("a non-time tag", 0x02, &b"\x05"[..]),
    ] {
        let as_not_before = certificate_with_times((tag, content), (0x17, b"451127000000Z"));
        assert_eq!(
            validity_window(&as_not_before),
            Err(OpenSshCertError::InvalidTime),
            "{name} in notBefore"
        );
        let as_not_after = certificate_with_times((0x17, b"260928000000Z"), (tag, content));
        assert_eq!(
            validity_window(&as_not_after),
            Err(OpenSshCertError::InvalidTime),
            "{name} in notAfter"
        );
    }
}

/// The published error is unchanged by the fix, which is the point of keeping
/// the field-and-fault detail private: a caller matching on
/// [`OpenSshCertError::InvalidTime`] still compiles and still gets the same
/// message, and the internal detail is asserted in the unit tests instead.
#[test]
fn the_published_error_variant_and_its_message_are_unchanged() {
    let before = certificate_with_times((0x18, b"20x50101000000Z"), (0x17, b"451127000000Z"));
    let after = certificate_with_times((0x17, b"260928000000Z"), (0x18, b"20x50101000000Z"));
    for der in [&before, &after] {
        assert_eq!(
            validity_window(der),
            Err(OpenSshCertError::InvalidTime),
            "a year of 20x5 is refused in either position"
        );
    }
    assert_eq!(
        OpenSshCertError::InvalidTime.to_string(),
        "invalid X.509 certificate time"
    );
}

/// A DER content octet string, short form, which is every length here.
fn der(tag: u8, content: &[u8]) -> Vec<u8> {
    let length = u8::try_from(content.len()).expect("test DER value is short-form");
    let mut encoded = vec![tag, length];
    encoded.extend_from_slice(content);
    encoded
}

/// A minimal Ed25519 certificate whose two validity fields carry exactly the
/// given tag and content octets.
///
/// It is structurally a real certificate — the same shape `openssl` writes, with
/// the times left alone — so the only thing under test is what the validity
/// parsing does with them. The public key is 32 zero bytes, which is a valid
/// Ed25519 point encoding and irrelevant to the times.
fn certificate_with_times(not_before: (u8, &[u8]), not_after: (u8, &[u8])) -> Vec<u8> {
    let algorithm = der(0x30, &der(0x06, &[0x2b, 0x65, 0x70]));

    let mut spki_content = algorithm.clone();
    spki_content.push(0x03);
    spki_content.push(33);
    spki_content.push(0);
    spki_content.extend_from_slice(&[0; 32]);
    let spki = der(0x30, &spki_content);

    let validity = der(
        0x30,
        &[
            der(not_before.0, not_before.1),
            der(not_after.0, not_after.1),
        ]
        .concat(),
    );

    let mut tbs_content = Vec::new();
    tbs_content.extend_from_slice(&der(0xa0, &der(0x02, &[2])));
    tbs_content.extend_from_slice(&der(0x02, &[7]));
    tbs_content.extend_from_slice(&algorithm);
    tbs_content.extend_from_slice(&der(0x30, &[]));
    tbs_content.extend_from_slice(&validity);
    tbs_content.extend_from_slice(&der(0x30, &[]));
    tbs_content.extend_from_slice(&spki);
    let tbs = der(0x30, &tbs_content);

    let mut certificate = tbs;
    certificate.extend_from_slice(&algorithm);
    certificate.extend_from_slice(&der(0x03, &[0]));
    der(0x30, &certificate)
}
